import numpy as np
from scipy import signal as sp_signal
from core.signal import Signal
from core.registry import register_operation

WINDOWS = {"Rectangular":"boxcar","Hann":"hann","Hamming":"hamming","Blackman":"blackman","Kaiser":"kaiser"}

class FFT:
    def apply(self,a,window="Hann",**_):
        wname=WINDOWS.get(window,"hann")
        w=sp_signal.get_window((wname,8.6) if wname=="kaiser" else wname,len(a.values))
        x=a.values*w
        X=np.fft.rfft(x)
        f=np.fft.rfftfreq(len(x),d=a.dt)
        mag=np.abs(X)/len(x)*2
        return Signal(f,mag,f"FFT | {a.name}",a.sampling_rate,{"operation":"FFT","window":window,"complex_spectrum":X,"original_fs":a.sampling_rate})
register_operation("FFT", FFT)

class IFFT:
    def apply(self,a,**_):
        X=a.metadata.get("complex_spectrum")
        if X is None:
            raise ValueError("IFFT requires an FFT result generated by this framework.")
        n=(len(X)-1)*2
        y=np.fft.irfft(X,n=n)
        fs=a.metadata.get("original_fs", a.sampling_rate) or 1.0
        t=np.arange(n)/fs
        return Signal(t,y,f"IFFT | {a.name}",fs,{"operation":"IFFT"})
register_operation("IFFT", IFFT)

class AMModulator:
    def apply(self, message, carrier_frequency=1000.0, modulation_index=0.5, **_):
        fs = message.sampling_rate
        if not fs or carrier_frequency >= fs/2:
            raise ValueError("Carrier frequency must be below Nyquist frequency.")
        t = message.time
        carrier = np.cos(2*np.pi*carrier_frequency*t)
        y = (1 + modulation_index*message.values)*carrier
        return Signal(t,y,f"AM({message.name})",fs,
                      {"operation":"AM modulation","carrier_frequency":carrier_frequency,"modulation_index":modulation_index})
register_operation("AM Modulation", AMModulator)

class AMDemodulator:
    def apply(self, a, carrier_frequency=1000.0, cutoff=100.0, **_):
        fs=a.sampling_rate
        if not fs: raise ValueError("Sampling rate is required.")
        if carrier_frequency >= fs/2: raise ValueError("Carrier frequency must be below Nyquist.")
        mixed = a.values * (2*np.cos(2*np.pi*carrier_frequency*a.time))
        if cutoff <= 0 or cutoff >= fs/2: raise ValueError("Demodulation cutoff must be below Nyquist.")
        sos=sp_signal.butter(5,cutoff,btype="lowpass",fs=fs,output="sos")
        y=sp_signal.sosfiltfilt(sos,mixed) if len(mixed)>30 else sp_signal.sosfilt(sos,mixed)
        return a.copy(name=f"AM demod({a.name})",values=y,metadata={"operation":"AM demodulation"})
register_operation("AM Demodulation", AMDemodulator)
